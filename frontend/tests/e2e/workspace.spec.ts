import { test, expect, Page } from '@playwright/test'

async function settled(page:Page){await expect(page.getByRole('button',{name:'筛选',exact:true})).toBeEnabled()}

test.beforeEach(async({page})=>{
  const login=await page.request.post('/api/auth/demo',{data:{actor:'operator_a'},headers:{'X-LLM4Web-Client':'web'}})
  expect(login.status()).toBe(200)
  await page.goto('/')
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(12)
  await settled(page)
})

test('advanced filters and saved query survive refresh and preserve the full query',async({page})=>{
  await page.getByLabel('收货城市',{exact:true}).selectOption('上海')
  await page.getByLabel('订单状态',{exact:true}).selectOption('paid')
  await page.locator('summary').filter({hasText:'高级筛选'}).click()
  await page.getByLabel('商品名称',{exact:true}).fill('商品01')
  await page.getByLabel('商品分类',{exact:true}).selectOption('数码')
  await page.getByLabel('金额上限',{exact:true}).fill('300')
  await page.getByRole('button',{name:'筛选',exact:true}).click()
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(4)
  await settled(page)
  await page.getByRole('button',{name:'保存当前查询',exact:true}).click()
  await page.getByLabel('查询名称',{exact:true}).fill('上海数码小额待发货')
  await page.getByRole('button',{name:'保存查询',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'常用查询设置'})).toHaveCount(0)
  await page.locator('.quick-views').getByRole('button',{name:'待发货',exact:true}).click()
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(8)
  await settled(page)
  await page.getByRole('button',{name:'应用常用查询 上海数码小额待发货',exact:true}).click()
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(4)
  await page.reload()
  await expect(page.getByRole('button',{name:'应用常用查询 上海数码小额待发货',exact:true})).toBeVisible()
  const state=await(await page.request.get('/api/session')).json()
  expect(state.current_result.query.filters.product_keyword).toBe('商品01')
  expect(state.current_result.query.filters.amount_lte).toBe('300')
  await page.getByRole('button',{name:'移除常用查询 上海数码小额待发货',exact:true}).click()
  await page.getByRole('button',{name:'确认移除',exact:true}).click()
  await expect(page.getByRole('button',{name:'应用常用查询 上海数码小额待发货',exact:true})).toHaveCount(0)
})

