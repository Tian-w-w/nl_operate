test('assistant navigation preserves analytics scope and the requested audit order',async({page})=>{
  async function tell(message:string){
    const input=page.getByRole('textbox',{name:'输入业务指令'})
    await expect(input).toBeEnabled()
    await input.fill(message)
    await page.getByRole('button',{name:'发送',exact:true}).click()
    await expect(input).toBeEnabled()
  }
  await page.getByLabel('收货城市',{exact:true}).selectOption('北京')
  await page.getByRole('button',{name:'筛选',exact:true}).click()
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(1)
  await settled(page)
  await page.getByRole('button',{name:'统计看板',exact:true}).click()
  await page.getByLabel('统计范围',{exact:true}).selectOption('all')
  await expect(page.locator('.insight-metrics')).toContainText('4,650.00')
  await tell('查看这些订单统计看板')
  await expect(page.getByLabel('统计范围',{exact:true})).toHaveValue('current')
  await expect(page.locator('.insight-metrics')).toContainText('120.00')
  await tell('查询上海已付款订单')
  await expect(page.locator('.orders-panel tbody tr')).toHaveCount(6)
  await tell('查看订单4的修改记录')
  await expect(page.getByLabel('审计订单编号')).toHaveValue('4')
  await expect(page.locator('.audit-feed article')).toHaveCount(1)
})
