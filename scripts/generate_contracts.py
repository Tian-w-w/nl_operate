"""Generate the TypeScript contracts from FastAPI's actual OpenAPI schemas."""
import argparse
import json
import re

from backend.app.config import ROOT, Settings
from backend.app.main import create_app

OUTPUT = ROOT / 'frontend/src/api-types.ts'


def name_for(value):
    return re.sub(r'[^A-Za-z0-9_]', '_', value)


def type_for(schema):
    if isinstance(schema, bool):
        return 'unknown' if schema else 'never'
    if '$ref' in schema:
        return name_for(schema['$ref'].rsplit('/', 1)[1])
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(v, ensure_ascii=False) for v in schema['enum'])
    for key in ['anyOf', 'oneOf']:
        if key in schema:
            return '(' + ' | '.join(type_for(v) for v in schema[key]) + ')'
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + type_for(schema['items']) + '>'
    if kind == 'object':
        if 'properties' in schema:
            required = set(schema.get('required', []))
            props = [f'{json.dumps(k)}{"" if k in required else "?"}: {type_for(v)}' for k, v in schema['properties'].items()]
            return '{ ' + '; '.join(props) + ' }'
        return 'Record<string, ' + type_for(schema.get('additionalProperties') or {}) + '>'
    if kind in {'integer', 'number'}:
        return 'number'
    if kind in {'boolean', 'string', 'null'}:
        return kind
    if schema == {} or set(schema).issubset({'title', 'description', 'default'}):
        return 'unknown'
    raise ValueError(f'Unsupported contract schema: {schema}')


def generate():
    schemas = create_app(settings=Settings(model_adapter='rules',model_enabled=False),serve_frontend=False).openapi()['components']['schemas']
    lines = ['// Generated by python -m scripts.generate_contracts. Do not edit.', '']
    lines += [f'export type {name_for(name)} = {type_for(value)}' for name, value in sorted(schemas.items())]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('API contracts drifted. Run python -m scripts.generate_contracts')
        print('API contracts match OpenAPI.')
    else:
        OUTPUT.write_text(generated, encoding='utf-8')
        print(f'Generated {OUTPUT}')


if __name__ == '__main__':
    main()
